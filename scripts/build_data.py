#!/usr/bin/env python3
"""Turn a Goodreads library export (data/goodreads_library_export.csv) into js/data.js.

Run from the project folder:  python3 scripts/build_data.py
Re-run it whenever you replace the CSV with a fresh export.
"""
import csv, json, os, re, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "data", "goodreads_library_export.csv")
OUT = os.path.join(ROOT, "js", "data.js")
COVERS = os.path.join(ROOT, "covers")


def norm(s):
    return re.sub(r"[^a-z0-9]", "", (s or "").lower())


def clean_title(t):
    # "Dune (Dune, #1)" -> "Dune"
    return re.sub(r"\s*\([^)]*#[^)]*\)\s*$", "", t).strip()


def series_of(t):
    m = re.search(r"\(([^)]*#[^)]*)\)\s*$", t)
    return m.group(1) if m else ""


def iso(d):
    return d.replace("/", "-") if d else ""


covers = sorted(f[:-4] for f in os.listdir(COVERS) if f.endswith(".jpg")) if os.path.isdir(COVERS) else []
cover_keys = sorted(((norm(c.replace("-", " ")), c) for c in covers), key=lambda x: -len(x[0]))


def cover_for(title):
    clean = clean_title(title)
    keys = {norm(title), norm(clean), norm(clean.split(":")[0])}
    for ck, slug in cover_keys:
        if ck in keys:
            return f"covers/{slug}.jpg"
    return ""


rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
books, current = [], []
for r in rows:
    rating = float(r["My Rating"] or 0)
    b = {
        "id": r["Book Id"],
        "title": clean_title(r["Title"]),
        "fullTitle": r["Title"],
        "series": series_of(r["Title"]),
        "author": r["Author"].replace("  ", " "),
        "rating": int(rating),
        "pages": int(r["Number of Pages"] or 0),
        "binding": r["Binding"],
        "dateRead": iso(r["Date Read"]),
        "dateAdded": iso(r["Date Added"]),
        "cover": cover_for(r["Title"]),
    }
    if r["Exclusive Shelf"] == "read":
        books.append(b)
    elif r["Exclusive Shelf"] == "currently-reading":
        current.append(b)

data = {
    "generated": datetime.date.today().isoformat(),
    "books": books,
    "currentlyReading": current,
    "covers": {k: f"covers/{s}.jpg" for k, s in cover_keys},
}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_data.py from your Goodreads export. Do not edit by hand.\n")
    f.write("window.GOODREADS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"Wrote {OUT}: {len(books)} read, {len(current)} currently reading, {len(covers)} covers")
